/** Resuelve el contenido de un proyecto en el idioma activo. */
export const localizeProject = (project, lang = 'es') => {
  if (!project) return null
  const copy = project[lang] || project.es
  return {
    ...project,
    ...copy,
    specs: {
      ...project.specs,
      bedrooms: copy.bedrooms ?? project.specs.bedrooms,
      bathrooms: copy.bathrooms ?? project.specs.bathrooms,
      garage: copy.garage,
    },
    team: DEFAULT_TEAM,
  }
}

